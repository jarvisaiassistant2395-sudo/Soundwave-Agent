#!/usr/bin/env node
// ── The paper that must travel with a bundled program ───────────────────────
// ffmpeg is a separate program bundled next to the app (mere aggregation, so it
// does not touch Soundwave's own licence), but GPLv3 requires its licence text
// and a written offer of corresponding source to accompany the binary. This
// writes both into desktop/bin/, where electron-builder's extraResources pick
// them up, so the installed app always carries them.
//
//   node scripts/write-binary-licenses.mjs [--bin <dir>]
//
// Called by desktop/assemble.mjs on every packaging run; also called by the CI
// step that fetches ffmpeg, so a build that only fetches the binary still ends
// up compliant. Safe to run repeatedly.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const argBin = process.argv.indexOf("--bin");
const binDir = argBin >= 0 && process.argv[argBin + 1] ? path.resolve(process.argv[argBin + 1]) : path.join(repoRoot, "desktop", "bin");

export function writeBinaryLicenses(bin = binDir) {
  const gplSource = path.join(repoRoot, "scripts", "licenses", "GPL-3.0-or-later.txt");
  if (!fs.existsSync(gplSource)) {
    throw new Error(`the GPLv3 text is missing from scripts/licenses/ — the installer would ship ffmpeg without it`);
  }
  fs.mkdirSync(bin, { recursive: true });
  fs.copyFileSync(gplSource, path.join(bin, "FFMPEG-LICENSE.txt"));
  const offer = [
    "SOUNDWAVE AI — WRITTEN OFFER OF CORRESPONDING SOURCE (FFmpeg)",
    "".padEnd(72, "="),
    "",
    "This product includes FFmpeg (ffmpeg.exe), a separate program distributed",
    "under the GNU General Public License, version 3 or later. It is included",
    "unmodified as a standalone executable and is invoked as a separate process;",
    "it is not linked into Soundwave AI, whose own code is proprietary and is",
    "unaffected by FFmpeg's licence.",
    "",
    "The binary was obtained from: https://www.gyan.dev/ffmpeg/builds/",
    "('release essentials' static 64-bit Windows build, licensed GPLv3).",
    "",
    "Corresponding source code for that exact build:",
    "  - FFmpeg upstream source: https://ffmpeg.org/download.html",
    "    (git://source.ffmpeg.org/ffmpeg.git)",
    "  - The build scripts and configuration used: https://github.com/GyanD/codexffmpeg",
    "  - Archived releases, including the one in this installer:",
    "    https://www.gyan.dev/ffmpeg/builds/ (see the 'complete archive' link)",
    "",
    "Soundwave AI will supply the corresponding source for the FFmpeg build shipped",
    "in this installer on request, in the preferred form for modification, for at",
    "least three years from the date of distribution, at no more than the cost of",
    "physically performing the transfer. Write to the address in the app's",
    "Settings → Help & Docs, or open an issue on the Soundwave AI repository.",
    "",
    "The full licence text travels with this offer as FFMPEG-LICENSE.txt",
    "(GNU GPL version 3, 29 June 2007).",
    "",
    `Generated by the build on ${new Date().toISOString()}.`,
    "",
  ].join("\n");
  fs.writeFileSync(path.join(bin, "FFMPEG-SOURCE-OFFER.txt"), offer);
  return ["FFMPEG-LICENSE.txt", "FFMPEG-SOURCE-OFFER.txt"].map((f) => path.join(bin, f));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const written = writeBinaryLicenses();
  for (const file of written) console.log(`[licences] wrote ${path.relative(repoRoot, file)}`);
}
